/** @type {import('next').NextConfig} */
const nextConfig = {
  // No special output needed for Vercel (default is 'server')
  // For GitHub Pages you would use output: 'export', but Vercel handles SSR natively.

  images: {
    // Allow remote patterns for GitHub avatars if needed
    remotePatterns: [],
    // Optimize local images
    formats: ['image/avif', 'image/webp'],
  },

  // Strict mode for catching React issues early
  reactStrictMode: true,

  // Security HTTP Headers (LAYER 5 requirement)
  async headers() {
    return [
      {
        source: '/(.*)',
        headers: [
          // Prevent clickjacking
          {
            key: 'X-Frame-Options',
            value: 'DENY',
          },
          // Prevent MIME-type sniffing
          {
            key: 'X-Content-Type-Options',
            value: 'nosniff',
          },
          // Control referrer information
          {
            key: 'Referrer-Policy',
            value: 'strict-origin-when-cross-origin',
          },
          // Restrict browser features
          {
            key: 'Permissions-Policy',
            value: 'camera=(), microphone=(), geolocation=()',
          },
          // Content Security Policy
          // Allows: local assets, Google Fonts, GitHub API
          {
            key: 'Content-Security-Policy',
            value: [
              "default-src 'self'",
              "script-src 'self' 'unsafe-inline' 'unsafe-eval'",
              "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
              "font-src 'self' https://fonts.gstatic.com",
              "img-src 'self' data: blob:",
              "connect-src 'self' https://api.github.com",
              "frame-ancestors 'none'",
              "base-uri 'self'",
              "form-action 'self'",
            ].join('; '),
          },
          // Additional XSS protection
          {
            key: 'X-XSS-Protection',
            value: '1; mode=block',
          },
        ],
      },
    ]
  },
}

export default nextConfig
